-- PREPARED, NOT APPLIED. Commercial Model V3 (docs/CORBAN-COMMERCIAL-MODEL-V3.md), foundation. Forward-only, additive, compatible with history.
-- No SECURITY DEFINER. No rename, no drop, no data rewritten. Legacy global tables (banks, providers, agreements, products, modalities) stay and keep working;
-- V3 adds tenant-owned layers next to them and relaxes (never removes) what a V3 route does not need.
--
-- Layers
--   1. Platform structure (global, read-only for tenants): contract_types (independent of any product) and national_agreement_templates (27 state governments /
--      Distrito Federal + 26 capital city halls; NOT tied to a bank; NOT active for anyone until a tenant enables them).
--   2. Tenant-owned catalog: organization_banks, organization_providers, organization_agreements (custom or enabled from a template), commission_groups (dynamic).
--   3. Routes: organization_product_routes gains org_bank_id / org_provider_id / org_agreement_id and its legacy columns become nullable; a CHECK allows exactly one
--      of the two shapes (all-legacy or V3). Tables, versions, checklists, proposals keep hanging on the route: nothing downstream changes.
--   4. Commercial conditions (per DRAFT table version; immutable once the version is published): contract type + term + coefficient/rate (readable by every member,
--      the simulation needs them) and, separately and supervisor+ only, the received commission and ONE share per commission group, all written in ONE call
--      (save_commercial_condition). Money/percentages are NUMERIC, never float.
--   3b. Payout policies (repasse por grupo): tenant-owned, immutable versions, % of the commission RECEIVED per group, gross or net base; applied to conditions by the RPC.
--       Groups are ALTERNATIVE sellers (Corretor OR Parceiro...), so caps are per group, never a sum. Route also carries Origem da Produção (own / third_party).
--   5. create_simulation_for_condition: governed simulation that takes coefficient/rate from the condition (commission is never copied).
-- Technical identifiers: every new tenant row gets an opaque tech_key generated by the database; users never type or see it.

